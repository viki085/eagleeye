"""A saved notebook manifest -> a Jupyter notebook (nbformat 4).

The export opens and re-runs in Jupyter: a setup cell loads the user's own copy of each input
file and defines save_table / save_stat. Outputs are plain text and PNG only — never HTML or
JavaScript — so nothing in a downloaded notebook can execute when it is opened.
"""

import base64
import json
from typing import Any

MAX_TABLE_ROWS = 20


def _lines(text: str) -> list[str]:
    """nbformat stores multi-line strings as a list of lines that keep their newlines."""
    if not text:
        return []
    parts = text.splitlines(keepends=True)
    return parts


def _markdown(text: str) -> dict[str, Any]:
    return {"cell_type": "markdown", "metadata": {}, "source": _lines(text)}


def _code(source: str, outputs: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": outputs,
        "source": _lines(source),
    }


def _stream(name: str, text: str) -> dict[str, Any]:
    return {"output_type": "stream", "name": name, "text": _lines(text)}


def _table_text(table: dict[str, Any]) -> str:
    columns = [str(c.get("name", "")) for c in table.get("columns", [])]
    rows = [[("" if v is None else str(v)) for v in r] for r in table.get("preview", [])]
    rows = rows[:MAX_TABLE_ROWS]
    widths = [
        max([len(c)] + [len(r[i]) for r in rows if i < len(r)]) for i, c in enumerate(columns)
    ]
    line = lambda cells: "  ".join(v.ljust(w) for v, w in zip(cells, widths, strict=False))  # noqa: E731
    shown = f" (first {len(rows)} of {table.get('row_count', len(rows))} rows)"
    body = "\n".join(line(r) for r in rows)
    return f"{table.get('title', 'table')}{shown}\n{line(columns)}\n{body}\n"


def _outputs(cell: dict[str, Any], figures: dict[str, bytes]) -> list[dict[str, Any]]:
    outputs: list[dict[str, Any]] = []
    if cell.get("stdout"):
        outputs.append(_stream("stdout", str(cell["stdout"])))
    for table in cell.get("tables", []):
        outputs.append(
            {
                "output_type": "display_data",
                "metadata": {},
                "data": {"text/plain": _lines(_table_text(table))},
            }
        )
    if cell.get("stats"):
        text = "".join(f"{k} = {v}\n" for k, v in cell["stats"].items())
        outputs.append(_stream("stdout", text))
    for name in cell.get("figures", []):
        png = figures.get(name)
        if png:
            outputs.append(
                {
                    "output_type": "display_data",
                    "metadata": {},
                    "data": {
                        "image/png": base64.b64encode(png).decode("ascii"),
                        "text/plain": [f"<Figure {name}>"],
                    },
                }
            )
    if cell.get("error"):
        outputs.append(_stream("stderr", f"{cell['error']}\n"))
    return outputs


def _setup(manifest: dict[str, Any]) -> str:
    loads = "\n".join(
        f'    "{i["name"]}": pd.read_csv({json.dumps(str(i["title"]) + ".csv")}),'
        for i in manifest.get("inputs", [])
    )
    return (
        "# Setup: point each entry at your own copy of the file (CSV or Excel).\n"
        "import pandas as pd\nimport numpy as np\nimport matplotlib.pyplot as plt\n"
        "import seaborn as sns\n\n"
        f"datasets = {{\n{loads}\n}}\n\n\n"
        "def save_table(name, df):\n    display(df)\n\n\n"
        'def save_stat(name, value):\n    print(f"{name} = {value}")\n'
    )


def to_ipynb(manifest: dict[str, Any], figures: dict[str, bytes]) -> dict[str, Any]:
    cells = [
        _markdown(
            f"# {manifest.get('title', 'Notebook')}\n\n"
            "Generated by EagleEye. The outputs below are from EagleEye's run; run the setup "
            "cell first to re-run it on your own copy of the data."
        ),
        _code(_setup(manifest), []),
    ]
    for cell in manifest.get("cells", []):
        status = "" if cell.get("status") in (None, "ok") else f" ({cell['status']})"
        cells.append(_markdown(f"## {cell.get('index', 0) + 1}. {cell.get('purpose', '')}{status}"))
        cells.append(_code(str(cell.get("code", "")), _outputs(cell, figures)))
    return {
        "nbformat": 4,
        "nbformat_minor": 5,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
        },
        "cells": [{**c, "id": f"cell-{i}"} for i, c in enumerate(cells)],
    }
