import React from "react";
import { AbsoluteFill, Audio, Sequence, staticFile, useCurrentFrame, useVideoConfig } from "remotion";
import { LogoOutro } from "../LogoOutro";
import { AdminSegment, type AdminPart } from "./Admin";
import { Headlines, ScalingChart } from "./Charts";
import { AMBER, DATA, FONT, GOLD, GREEN, INK, MONO, MUTED, TIMELINE, clamp01, fmt, usersAt, type LoadScene, type Part } from "./data";
import { K6Log, Scanlines, Typed, UserCounter, appear, glitch } from "./Hacker";
import { Wall } from "./Wall";

const BRIEFING = [
  "> EAGLEEYE LOAD TEST",
  "> TARGET   1 → 50 → 500 → 1,000 → 2,000 CONCURRENT USERS",
  "> MIX      90% DOCUMENTS · 6% DATABASE & CHARTS · 3% ATTACKS · 1% NOTEBOOKS",
  "> STACK    AWS ECS FARGATE · AUTOSCALING ON THE ANSWER QUEUE",
  "> k6 run --profile run",
];

const Briefing: React.FC<{ t: number }> = ({ t }) => (
  <AbsoluteFill style={{ background: "#010302", padding: "190px 150px" }}>
    <Typed lines={BRIEFING} t={t - 0.4} />
    <div style={{ position: "absolute", left: 150, bottom: 120, fontFamily: FONT, fontSize: 26, color: MUTED, opacity: appear(t, 6) }}>
      AI model simulated for the load test · everything else real: sign-in, API, queue, workers, databases, sandbox
    </div>
    <Scanlines />
  </AbsoluteFill>
);

const WallScene: React.FC<{ part: Part; t: number; fps: number }> = ({ part, t, fps }) => {
  const frame = useCurrentFrame();
  const stages = part.stages as [number, number][];
  const [r0, r1] = part.run as [number, number];
  const until = (part.until as number | undefined) ?? 999;
  const [stageAt, n] = [...stages].reverse().find(([at]) => t >= at) ?? stages[0];
  const span = Math.min(until, stages.at(-1)![0] + 2.5);
  const runT = r0 + (r1 - r0) * clamp01(t / span);
  const out = until < 999 ? clamp01((until - t) / 0.3) : 1;
  return (
    <AbsoluteFill style={{ opacity: out, ...glitch(frame, Boolean(part.glitch)) }}>
      <Wall n={n} sinceStage={t - stageAt} fps={fps} />
      <div style={{ position: "absolute", left: 56, bottom: 50 }}>
        <K6Log runT={runT} rows={n >= 64 ? 12 : 16} />
      </div>
      <UserCounter users={usersAt(runT)} />
      {n > 8 && (
        <div style={{ position: "absolute", right: 64, bottom: 50, fontFamily: MONO, fontSize: 19, color: `${GREEN}bb`, background: "rgba(0,10,4,0.8)", padding: "8px 14px", borderRadius: 8 }}>
          sample sessions shown · {fmt(usersAt(runT))} users generated by k6
        </div>
      )}
      <Scanlines />
    </AbsoluteFill>
  );
};

const Results: React.FC<{ part: Part; t: number }> = ({ part, t }) => {
  const [r0, r1] = part.run as [number, number];
  const runT = r0 + (r1 - r0) * clamp01(t / 7);
  const tot = DATA.totals;
  const rows: [string, string][] = [
    ["Peak users", "2,000"],
    ["Answers", fmt(tot.answers)],
    ["Failed", `${tot.errors} (${((100 * tot.errors) / tot.answers).toFixed(2)}%)`],
    ["Response time", `avg ${tot.avg_s.toFixed(1)} s · p95 ${tot.p95_s.toFixed(1)} s`],
    ["Peak servers", `${tot.peak_tasks["agent-worker"]} agent workers · ${tot.peak_tasks.api} API`],
    ["LLM cost (estimated)", "$6.41 · model simulated"],
  ];
  return (
    <AbsoluteFill style={{ background: "#010302" }}>
      <UserCounter users={usersAt(runT)} />
      <div style={{ position: "absolute", left: 150, top: 190, fontFamily: MONO, color: GREEN }}>
        <div style={{ fontSize: 26, letterSpacing: 6, opacity: 0.8 }}>RESULTS</div>
        {rows.map(([k, v], i) => (
          <div key={k} style={{ display: "flex", gap: 40, fontSize: 40, marginTop: 26, opacity: appear(t, 1 + i * 0.45) }}>
            <span style={{ width: 470, color: `${GREEN}aa` }}>{k}</span>
            <span style={{ color: k.startsWith("LLM") ? AMBER : GREEN }}>{v}</span>
          </div>
        ))}
        <div style={{ marginTop: 52, fontSize: 26, color: `${GREEN}99`, opacity: appear(t, 4.5) }}>{"> terraform destroy   ✓ 76 destroyed"}</div>
      </div>
      <Scanlines />
    </AbsoluteFill>
  );
};

const Summary: React.FC<{ t: number }> = ({ t }) => {
  const reveal: [number, number, number] = [appear(t, 0.2, 1), appear(t, 2.4, 1), appear(t, 4.6, 1)];
  return (
    <AbsoluteFill style={{ background: "#0b0b0a" }}>
      <ScalingChart upTo={23} reveal={reveal} labels={3} title="What scaling changed" />
      <Headlines opacity={appear(t, 8, 0.8)} />
    </AbsoluteFill>
  );
};

function renderPart(scene: LoadScene, part: Part, t: number, fps: number): React.ReactNode {
  switch (part.type) {
    case "briefing": return <Briefing t={t} />;
    case "wall": return <WallScene part={part} t={t} fps={fps} />;
    case "admin": {
      const p = part as unknown as AdminPart;
      return t >= p.at && t <= p.holdUntil + 0.3 ? <AdminSegment part={p} t={t} fps={fps} /> : null;
    }
    case "chart": {
      const at = part.at;
      const end = part.end as number;
      if (t < at || t > end) return null;
      const upTo = Math.min(part.upTo as number, 1 + ((part.upTo as number) - 1) * clamp01((t - at) / 3.2));
      const labels = scene.n === 9 ? 1 : scene.n === 10 ? 2 : 3;
      return (
        <AbsoluteFill style={{ opacity: clamp01((t - at) / 0.35) * clamp01((end - t) / 0.3 + (scene.n === 11 ? 1 : 0)) }}>
          <ScalingChart upTo={upTo} labels={labels} title="Response time as the cluster scales" />
        </AbsoluteFill>
      );
    }
    case "results": return <Results part={part} t={t} />;
    case "summary": return <Summary t={t} />;
    default: return null;
  }
}

/** One scene: its parts, each in a Sequence starting at the part's time (videos start there). */
const SceneView: React.FC<{ scene: LoadScene }> = ({ scene }) => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const t = frame / fps;
  if (scene.parts[0]?.type === "logo") return <LogoOutro />;
  return (
    <AbsoluteFill style={{ background: "#000" }}>
      {scene.parts.map((p, i) => {
        const from = Math.round((p.type === "admin" ? p.at : 0) * fps);
        return (
          <Sequence key={i} from={from} layout="none">
            <PartAt scene={scene} part={p} offset={from / fps} />
          </Sequence>
        );
      })}
      {scene.n >= 9 && scene.n <= 11 && t < 0.6 && (
        <AbsoluteFill style={{ background: GOLD, opacity: 0.12 * (1 - t / 0.6) }} />
      )}
    </AbsoluteFill>
  );
};

const PartAt: React.FC<{ scene: LoadScene; part: Part; offset: number }> = ({ scene, part, offset }) => {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  return <>{renderPart(scene, part, frame / fps + offset, fps)}</>;
};

/** Part 2: the load test. */
export const LoadTest: React.FC = () => {
  const { fps } = useVideoConfig();
  return (
    <AbsoluteFill style={{ background: "#000", color: INK }}>
      {TIMELINE.scenes.map((s) => (
        <Sequence key={s.n} from={Math.round(s.start * fps)} durationInFrames={Math.round(s.length * fps)}>
          <SceneView scene={s} />
        </Sequence>
      ))}
      {TIMELINE.lines.map((l) => (
        <Sequence key={l.id} from={l.from} durationInFrames={l.frames}>
          <Audio src={staticFile(l.src)} />
        </Sequence>
      ))}
    </AbsoluteFill>
  );
};
